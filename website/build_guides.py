#!/usr/bin/env python3
"""Render the first-party guide and reference pages. Use --check to detect drift."""
import argparse
import hashlib
import json
from html import escape
from pathlib import Path
import re
import sys
from string import Template

ROOT = Path(__file__).resolve().parent
SOURCES = ROOT / 'guides'
PUBLIC = ROOT / 'public'
ORIGIN = 'https://gitturtle.com'
MARKER = '<!-- Generated by website/build_guides.py. Edit the source in website/guides/. -->'
METADATA = re.compile(r'<!-- title: (.+?) -->\n<!-- description: (.+?) -->\n')
DOCS = (
    ('/docs/', 'All guides'),
    ('/docs/first-repository/', 'Your first repository'),
    ('/docs/history-and-diffs/', 'History and diffs'),
    ('/docs/staging/', 'Stage and commit'),
    ('/docs/worktrees-and-recovery/', 'Worktrees and recovery'),
    ('/docs/github/', 'GitHub pull requests'),
    ('/docs/previews-and-keyboard/', 'Previews and shortcuts'),
    ('/docs/omarchy-and-themes/', 'Omarchy and themes'),
)
INSTALL = (
    ('/install/', 'Installation overview'),
    ('/install/macos/', 'macOS'),
    ('/install/arch-omarchy/', 'Arch and Omarchy'),
    ('/install/ubuntu/', 'Ubuntu'),
)
REFERENCE = (
    ('/performance/', 'Performance'),
    ('/releases/', 'Release status'),
    ('/support/', 'Support'),
    ('/legal/', 'License and notices'),
)


def nav_link(url, label, route):
    current = ' aria-current="page"' if route == url else ''
    return f'<a href="{url}"{current}>{escape(label)}</a>'


def load_pages():
    pages = {}
    for source in sorted(SOURCES.rglob('*.html')):
        if source.parent == SOURCES:
            continue  # Shared document template.
        path = source.relative_to(SOURCES).with_suffix('')
        if path.parts[0] == 'reference':
            path = path.relative_to('reference')
        if path.name == 'index':
            path = path.parent
        route = '/' + path.as_posix() + '/'
        if route in pages:
            raise ValueError(f'Duplicate route {route} in {source}')
        fragment = source.read_text(encoding='utf-8')
        metadata = METADATA.match(fragment)
        if not metadata:
            raise ValueError(f'{source}: start with title and description comments')
        pages[route] = (*metadata.groups(), fragment[metadata.end():].strip())
    missing = {route for route, _ in (*DOCS, *INSTALL, *REFERENCE)} - pages.keys()
    if missing:
        raise ValueError('Missing source fragments for ' + ', '.join(sorted(missing)))
    return pages


def render(template, route, title, description, body):
    if route.startswith('/docs/'):
        section, links = 'Documentation', DOCS
    elif route.startswith('/install/'):
        section, links = 'Installation', INSTALL
    else:
        section, links = 'Project information', REFERENCE
    sidebar = '\n'.join(nav_link(url, label, route) for url, label in links)
    crumb_links = [('/', 'Home')]
    if route.startswith('/docs/') and route != '/docs/':
        crumb_links.append(('/docs/', 'Docs'))
    elif route.startswith('/install/') and route != '/install/':
        crumb_links.append(('/install/', 'Installation'))
    crumb_links.append((route, dict(links)[route]))
    crumbs = ''.join(f'<li>{nav_link(url, label, route)}</li>' for url, label in crumb_links)
    breadcrumb_data = {
        '@context': 'https://schema.org', '@type': 'BreadcrumbList',
        'itemListElement': [
            {'@type': 'ListItem', 'position': index, 'name': label, 'item': ORIGIN + url}
            for index, (url, label) in enumerate(crumb_links, start=1)
        ],
    }
    scripts = []
    if 'data-screenshot=' in body:
        scripts.append('  <script defer src="/site.js"></script>\n')
    if '<pre>' in body:
        scripts.append('  <script defer src="/guide.js"></script>\n')
    return template.substitute(
        crumbs=crumbs, breadcrumb_data=json.dumps(breadcrumb_data, ensure_ascii=False),
        page_title=escape(title if 'GitTurtle' in title else f'{title} | GitTurtle'),
        guide_scripts=''.join(scripts),
        marker=MARKER, title=escape(title), description=escape(description),
        canonical=ORIGIN + route, section=section, sidebar=sidebar, body=body,
        docs_current=' aria-current="page"' if route == '/docs/' else '',
        install_current=' aria-current="page"' if route == '/install/' else '',
    )


REPO_ROOT = ROOT.parent
LOCAL_MD_LINK = re.compile(r'(?<!\!)\[([^\]]+)\]\((?!https?://|mailto:|#)([^)]+)\)', re.IGNORECASE)


def _read_regular_text(path: Path, label: str) -> str:
    if path.is_symlink():
        raise ValueError(f'Refusing symlinked legal source {label}: {path}')
    return path.read_text(encoding='utf-8')


def _rewrite_local_md_link(match: re.Match) -> str:
    label, target = match.group(1), match.group(2)
    if label.strip('`').strip() == target.strip():
        return label
    return f'{label} ({target})'


def render_legal_notices(repo_root=REPO_ROOT):
    """Generate website/public/legal/notices/* deterministically from repository legal sources."""
    repo_root = Path(repo_root).resolve()
    public_root = repo_root / 'website' / 'public'
    license_text = _read_regular_text(repo_root / 'LICENSE', 'LICENSE')
    raw_third_party = _read_regular_text(repo_root / 'THIRD_PARTY_NOTICES.md', 'THIRD_PARTY_NOTICES.md')
    # Rewrite relative repository Markdown links into plain readable references for standalone .txt serving.
    third_party_text = LOCAL_MD_LINK.sub(_rewrite_local_md_link, raw_third_party)

    assets_dir = repo_root / 'docs' / 'licenses' / 'assets'
    sources_path = assets_dir / 'sources.json'
    sources = json.loads(_read_regular_text(sources_path, 'docs/licenses/assets/sources.json'))
    if not isinstance(sources, list) or not sources:
        raise ValueError('docs/licenses/assets/sources.json must be a non-empty list')
    expected_names = set()
    sections = [
        'GitTurtle artwork, theme, font and native-library notices',
        '',
        'Each section reproduces a notice from the source checkout.',
    ]
    for entry in sorted(sources, key=lambda item: item['file']):
        name = entry['file']
        if not isinstance(name, str) or '/' in name or '\\' in name or name in {'', '.', '..'}:
            raise ValueError(f'Invalid notice filename in sources.json: {name!r}')
        expected_names.add(name)
        path = assets_dir / name
        if path.is_symlink() or not path.is_file():
            raise ValueError(f'Missing or symlinked notice file: docs/licenses/assets/{name}')
        data = path.read_bytes()
        expected_sha = entry.get('sha256')
        if expected_sha and hashlib.sha256(data).hexdigest() != expected_sha:
            raise ValueError(f'SHA-256 mismatch for docs/licenses/assets/{name}')
        sections.extend([
            '',
            f'===== docs/licenses/assets/{name} =====',
            '',
            data.decode('utf-8').replace('\r\n', '\n').replace('\r', '\n').rstrip('\n'),
        ])
    unexpected = sorted(
        p.name for p in assets_dir.iterdir()
        if not p.name.startswith('.') and p.name != 'sources.json' and p.name not in expected_names
    )
    if unexpected:
        raise ValueError('Unexpected unmanifested files in docs/licenses/assets/: ' + ', '.join(unexpected))
    artwork_text = '\n'.join(sections) + '\n'
    notices_dir = public_root / 'legal' / 'notices'
    return {
        notices_dir / 'gitturtle-license.txt': license_text,
        notices_dir / 'third-party-notices.txt': third_party_text,
        notices_dir / 'artwork-themes-fonts.txt': artwork_text,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='compare against the published files')
    args = parser.parse_args()
    template = Template((SOURCES / 'page.html').read_text(encoding='utf-8'))
    pages = load_pages()
    outputs = set()
    problems = []
    for route, content in pages.items():
        target = PUBLIC / route.strip('/') / 'index.html'
        outputs.add(target)
        html = render(template, route, *content)
        if target.is_symlink():
            problems.append(f'Refusing symlinked generated file {target.relative_to(ROOT)}')
            continue
        if target.exists() and target.read_text(encoding='utf-8') == html:
            continue
        if args.check:
            problems.append(f'Stale or missing {target.relative_to(ROOT)}')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(html, encoding='utf-8')
    for target in PUBLIC.rglob('index.html'):
        if target not in outputs and not target.is_symlink() and MARKER in target.read_text(encoding='utf-8'):
            problems.append(f'Remove the obsolete generated file {target.relative_to(ROOT)}')
    notices = render_legal_notices()
    for target, text in notices.items():
        if target.is_symlink():
            problems.append(f'Refusing symlinked legal notice {target.relative_to(ROOT)}')
            continue
        if target.exists() and target.read_text(encoding='utf-8') == text:
            continue
        if args.check:
            problems.append(f'Stale or missing legal notice {target.relative_to(ROOT)}')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding='utf-8')
    if problems:
        sys.exit('\n'.join(problems))
    verb = 'verified' if args.check else 'rendered'
    print(f'{len(outputs)} static pages and {len(notices)} legal notices {verb}.')


if __name__ == '__main__':
    main()
