#!/usr/bin/env python3
"""Generate and verify thin Claude Code and Codex adapters from canonical `.agents/` definitions.

Canonical sources live in:
  - `.agents/roles/<name>.md` (tool-neutral role contracts, zero model/effort pinning)
  - `.agents/skills/<name>/SKILL.md` (open Agent Skills standard)

Generated adapters:
  - `.claude/agents/<name>.md`
  - `.codex/agents/<name>.toml`
  - `.claude/skills/<name>` -> `../../.agents/skills/<name>` symlinks
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
import os
from pathlib import Path
import re
import shutil
import sys

ROOT = Path(__file__).resolve().parents[2]
ROLE_NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
FORBIDDEN_ROLE_KEYS = frozenset({"model", "effort", "model_reasoning_effort", "reasoning_effort"})
GENERATED_MD_NOTE = (
    "<!-- Generated by scripts/dev/sync_adapters.py from .agents/roles/{name}.md. "
    "Edit the canonical role and rerun sync_adapters.py --write. -->"
)
GENERATED_TOML_NOTE = (
    "# Generated by scripts/dev/sync_adapters.py from .agents/roles/{name}.md.\n"
    "# Edit the canonical role and rerun sync_adapters.py --write.\n"
)


@dataclass(frozen=True)
class RoleSpec:
    name: str
    description: str
    claude_tools: str
    claude_disallowed_tools: str
    claude_permission_mode: str
    claude_max_turns: str
    codex_sandbox: str
    body: str


def parse_role(path: Path) -> RoleSpec:
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    if not lines or lines[0] != "---":
        raise ValueError(f"{path}: role must begin with --- frontmatter")
    try:
        end = lines.index("---", 1)
    except ValueError as error:
        raise ValueError(f"{path}: role frontmatter has no closing ---") from error
    fields: dict[str, str] = {}
    for raw in lines[1:end]:
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        match = re.match(r"^([A-Za-z][A-Za-z0-9_-]*):\s*(.*)$", raw)
        if not match:
            raise ValueError(f"{path}: unreadable frontmatter line: {raw!r}")
        key, value = match.groups()
        if key in FORBIDDEN_ROLE_KEYS:
            raise ValueError(f"{path}: role must omit {key!r} to inherit session settings")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]
        fields[key] = value
    name = fields.get("name", "").strip()
    if not name or name != path.stem or not ROLE_NAME_RE.match(name):
        raise ValueError(f"{path}: role name {name!r} must match lowercase-hyphenated filename")
    description = fields.get("description", "").strip()
    if not description:
        raise ValueError(f"{path}: role requires a nonempty description")
    body = "\n".join(lines[end + 1 :]).strip()
    if not body:
        raise ValueError(f"{path}: role requires instructions after frontmatter")
    codex_sandbox = fields.get("codex_sandbox", "read-only").strip()
    if codex_sandbox not in {"read-only", "workspace-write"}:
        raise ValueError(f"{path}: codex_sandbox must be read-only or workspace-write")
    return RoleSpec(
        name=name,
        description=description,
        claude_tools=fields.get("claude_tools", "Read, Grep, Glob, Bash").strip(),
        claude_disallowed_tools=fields.get("claude_disallowed_tools", "").strip(),
        claude_permission_mode=fields.get("claude_permission_mode", "dontAsk").strip(),
        claude_max_turns=fields.get("claude_max_turns", "").strip(),
        codex_sandbox=codex_sandbox,
        body=body,
    )


def render_claude_agent(role: RoleSpec) -> str:
    header = [
        "---",
        f"name: {role.name}",
        f"description: {role.description}",
    ]
    if role.claude_tools:
        header.append(f"tools: {role.claude_tools}")
    if role.claude_disallowed_tools:
        header.append(f"disallowedTools: {role.claude_disallowed_tools}")
    if role.claude_permission_mode:
        header.append(f"permissionMode: {role.claude_permission_mode}")
    if role.claude_max_turns:
        header.append(f"maxTurns: {role.claude_max_turns}")
    header.append("---")
    note = GENERATED_MD_NOTE.format(name=role.name)
    return "\n".join(header) + "\n" + note + "\n" + role.body + "\n"


def _toml_multiline(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return '"""\n' + escaped + '\n"""'


def render_codex_agent(role: RoleSpec) -> str:
    return (
        GENERATED_TOML_NOTE.format(name=role.name)
        + f"name = {json.dumps(role.name)}\n"
        + f"description = {json.dumps(role.description)}\n"
        + f"sandbox_mode = {json.dumps(role.codex_sandbox)}\n"
        + f"developer_instructions = {_toml_multiline(role.body)}\n"
    )


def load_roles(root: Path) -> list[RoleSpec]:
    roles_dir = root / ".agents" / "roles"
    if not roles_dir.is_dir():
        return []
    return [parse_role(path) for path in sorted(roles_dir.glob("*.md"))]


def canonical_skills(root: Path) -> list[str]:
    skills_dir = root / ".agents" / "skills"
    if not skills_dir.is_dir():
        return []
    return sorted(
        entry.name
        for entry in skills_dir.iterdir()
        if entry.is_dir() and not entry.is_symlink() and (entry / "SKILL.md").is_file()
    )


def sync(root: Path, *, write: bool) -> list[str]:
    issues: list[str] = []
    roles = load_roles(root)
    claude_agents = root / ".claude" / "agents"
    codex_agents = root / ".codex" / "agents"

    if roles:
        expected_claude = {f"{role.name}.md": render_claude_agent(role) for role in roles}
        expected_codex = {f"{role.name}.toml": render_codex_agent(role) for role in roles}

        for directory, expected in ((claude_agents, expected_claude), (codex_agents, expected_codex)):
            if write:
                directory.mkdir(parents=True, exist_ok=True)
            existing = {p.name: p for p in directory.iterdir()} if directory.is_dir() else {}
            for name, path in sorted(existing.items()):
                if name not in expected:
                    if write:
                        if path.is_dir() and not path.is_symlink():
                            shutil.rmtree(path)
                        else:
                            path.unlink()
                    else:
                        issues.append(f"stale adapter file not in .agents/roles/: {path.relative_to(root)}")
            for name, content in sorted(expected.items()):
                target = directory / name
                current = target.read_text(encoding="utf-8") if target.is_file() else None
                if current != content:
                    if write:
                        target.write_text(content, encoding="utf-8")
                    else:
                        issues.append(f"adapter out of sync with .agents/roles/: {target.relative_to(root)}")

    skills = canonical_skills(root)
    claude_skills = root / ".claude" / "skills"
    if skills and (claude_skills.exists() or (root / ".claude").is_dir()):
        if write:
            claude_skills.mkdir(parents=True, exist_ok=True)
        existing_skills = {p.name: p for p in claude_skills.iterdir()} if claude_skills.is_dir() else {}
        expected_skill_set = set(skills)
        for name, path in sorted(existing_skills.items()):
            if name not in expected_skill_set:
                if write:
                    if path.is_dir() and not path.is_symlink():
                        shutil.rmtree(path)
                    else:
                        path.unlink()
                else:
                    issues.append(f"extra skill under .claude/skills/ not in .agents/skills/: {path.relative_to(root)}")
        for name in skills:
            link = claude_skills / name
            wanted = f"../../.agents/skills/{name}"
            if link.is_symlink() and os.readlink(link) == wanted:
                continue
            if write:
                if link.is_symlink() or link.is_file():
                    link.unlink()
                elif link.is_dir():
                    shutil.rmtree(link)
                link.symlink_to(wanted)
            else:
                issues.append(f"expected symlink {link.relative_to(root)} -> {wanted}")

    return issues


def check_sync(root: Path) -> list[str]:
    try:
        return sync(root, write=False)
    except ValueError as error:
        return [str(error)]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate or verify Claude/Codex adapters from .agents/.")
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="write adapters and skill symlinks")
    group.add_argument("--check", action="store_true", help="verify adapters and skill symlinks are in sync")
    args = parser.parse_args(argv)

    root = args.root.resolve()
    try:
        issues = sync(root, write=args.write)
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    if issues:
        for issue in issues:
            print(f"adapter sync: {issue}", file=sys.stderr)
        return 1
    roles = load_roles(root)
    skills = canonical_skills(root)
    verb = "Synced" if args.write else "Verified"
    print(f"{verb} {len(roles)} roles and {len(skills)} skills.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
